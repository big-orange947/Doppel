def build_dataset() -> dict[str, Any]:
    cases = [
        {
            "case_id": case_id,
            "partition": partition,
            "category": category,
            "query": query,
            "expected_entity_mentions": list(entities),
            "expected_path_steps": [
                {"relation_types": [relation_type], "direction": direction}
                for relation_type, direction in steps
            ],
            "traits": list(traits),
            "forbidden_relation_types": list(forbidden),
        }
        for (
            case_id,
            partition,
            category,
            query,
            entities,
            steps,
            traits,
            forbidden,
        ) in CASES
    ]
    payload: dict[str, Any] = {
        "suite": "doppel-relation-path-planner-zh-v2",
        "suite_version": "2.0.0-sealed.1",
        "frozen": True,
        "publication_ready": False,
        "relation_catalog": "../catalogs/personal-relations-v1.json",
        "cases": cases,
    }
    encoded = json.dumps(
        payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    payload["fingerprint"] = hashlib.sha256(encoded).hexdigest()
    return payload


def main() -> None:
    target = (
        Path(__file__).parent
        / "datasets"
        / "relation-path-planner-quality-zh-v2.json"
    )
    target.write_text(
        json.dumps(build_dataset(), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
